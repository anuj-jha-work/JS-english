//switch statement
const month=5;
switch(month) {
    case 1:
        console.log("January");
        break;
    case "feb":
        console.log("February");
        break;
    case 3:
        console.log("March");
        break;
    case "april":
        console.log("April");
        break;
    case 5:
        console.log("May"); 
        break;
    default:
        console.log("Any other month");
        break;
}